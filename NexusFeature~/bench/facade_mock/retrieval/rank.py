"""Offline reproduction of Codex CLI 0.160.0 `tool_search` ranking over Unity / Nexus tool surfaces.

Fidelity (see A_tool_search.md for citations):
  * search text per MCP tool = build_mcp_search_text() in codex-rs/core/src/tools/handlers/mcp.rs:
      "<mcp__server__tool> <callable_name> <tool.name> <server_name> [title] [description]
       [namespace_description(=server instructions)] <sorted TOP-LEVEL inputSchema.properties keys>"
  * ranking = bm25 crate 2.3.2, SearchEngineBuilder::with_documents(Language::English) (k1=1.2, b=0.75,
    avgdl fitted, NLTK stopwords, Snowball English stemmer, UAX#29 word split) -> executed by the real crate
    via ./bm25_ranker (Rust), not a re-implementation.
  * default limit = 8 (TOOL_SEARCH_DEFAULT_LIMIT).
Ties: the crate sorts a HashSet-derived vector (unstable order across processes); we report the pessimistic
rank (all tied docs ahead) as the headline and the optimistic rank alongside.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

import tiktoken

HERE = Path(__file__).resolve().parent
EVID = HERE.parents[2] / "v2_analysis" / "F_facade_evidence"
RANKER = os.environ.get("BM25_RANKER", str(HERE / "bm25_ranker" / "target" / "release" / "bm25_ranker"))
ENC = tiktoken.get_encoding("o200k_base")
LIMIT = 8


def unity_tools():
    lines = [json.loads(l) for l in open(EVID / "unity_mcp_tools_list.jsonl")]
    return next(l for l in lines if l.get("id") == 2)["result"]["tools"]


def nexus_tools():
    return json.load(open(HERE / "data" / "nexus_tools.json"))


def catalog_surface(fname):
    """S6 surfaces generated by the catalog agent (bench/facade_mock/catalog/*.json, tools/list shape)."""
    p = HERE.parent / "catalog" / fname
    if not p.exists():
        return None
    return json.load(open(p))["result"]["tools"]


def tool_actions(tool):
    """Unity command names a catalog tool can dispatch to (action == unity command name, per catalog_groups.json)."""
    s = tool.get("inputSchema", {})
    acts = set()
    for b in s.get("oneOf", []):
        a = b.get("properties", {}).get("action", {})
        acts |= {a["const"]} if "const" in a else set(a.get("enum", []))
    a = s.get("properties", {}).get("action", {})
    acts |= set(a.get("enum", [])) | ({a["const"]} if "const" in a else set())
    return acts


def search_text(tool: dict, server: str, instructions: str | None = None) -> str:
    ns = "mcp__" + server.replace("-", "_") + "__"
    props = sorted((tool.get("inputSchema") or {}).get("properties", {}) or {})
    parts = [ns + tool["name"], tool["name"], tool["name"], server]
    if tool.get("title"):
        parts.append(tool["title"].strip())
    if tool.get("description"):
        parts.append(tool["description"].strip())
    if instructions:
        parts.append(instructions.strip())
    parts.extend(props)
    return " ".join(parts)


def enrich_nexus(tool: dict) -> dict:
    """HYPOTHETICAL: what if a Nexus manager's description listed its oneOf actions (Codex only indexes the
    top-level description + top-level property names, so oneOf variant text is invisible to tool_search)."""
    s = tool.get("inputSchema", {})
    if "oneOf" not in s:
        return tool
    bits = []
    for v in s["oneOf"]:
        props = v.get("properties", {})
        a = props.get("action") or props.get("strategy") or props.get("condition") or {}
        name = a.get("const") or (a.get("enum") or [""])[0]
        bits.append(f"{name}: {v.get('description', '')}".strip())
    t = dict(tool)
    t["description"] = tool["description"] + ". Actions: " + "; ".join(bits)
    return t


def bm25(docs: list[str], queries: list[str]):
    out = subprocess.run([RANKER], input=json.dumps({"docs": docs, "queries": queries}),
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def tool_tokens(tool: dict) -> int:
    return len(ENC.encode(json.dumps({"name": tool["name"], "description": tool.get("description", ""),
                                      "parameters": tool.get("inputSchema", {})})))


def cc_keyword_rank(entries, query):
    r"""Claude Code 2.1.286 ToolSearch keyword path (function VWn in the bundled cli; see A_tool_search.md).
    MCP tool: parts = [server, tool] lowercased, split on [\s_.]+ ; coarseParts = [server, tool];
    per term: part exact +12 | part substring +6 ; coarse exact +12 | coarse substring +4 ;
    full-name substring +3 only if score still 0 ; searchHint \bterm\b +4 ; description \bterm\b +2.
    Terms = query.lower().split() (no stemming, no stopwords). score>0, stable sort desc, top max_results(5).
    '+term' (required) and 'select:' / exact-name paths are not exercised by our queries."""
    q = query.lower().strip()
    for i, (srv, t) in enumerate(entries):  # exact full-name shortcut
        if ("mcp__%s__%s" % (srv, t["name"])).lower() == q:
            return [(i, 1e9)]
    terms = [x for x in q.split() if x]
    out = []
    for i, (srv, t) in enumerate(entries):
        coarse = [srv.lower(), t["name"].lower()]
        parts = [p for c in coarse for p in re.split(r"[\s_.]+", c) if p]
        full = " ".join(parts)
        desc = (t.get("description") or "")[:2048].lower()
        hint = ((t.get("_meta") or {}).get("anthropic/searchHint") or "").lower()
        sc = 0
        for term in terms:
            rx = re.compile(r"\b" + re.escape(term) + r"\b")
            if term in parts:
                sc += 12
            elif any(term in p for p in parts):
                sc += 6
            if term in coarse:
                sc += 12
            elif any(term in c for c in coarse):
                sc += 4
            if term in full and sc == 0:
                sc += 3
            if hint and rx.search(hint):
                sc += 4
            if rx.search(desc):
                sc += 2
        if sc > 0:
            out.append((i, float(sc)))
    out.sort(key=lambda x: -x[1])  # stable, like JS Array.prototype.sort
    return out


def evaluate(surface: str, entries: list[tuple[str, dict]], intents: list[dict], field: str, label_fn,
             ranker: str = "codex"):
    """entries: list of (server, tool)."""
    docs = [search_text(t, srv) for srv, t in entries]
    names = [t["name"] for _, t in entries]
    servers = [srv for srv, _ in entries]
    toks = [tool_tokens(t) for _, t in entries]
    if ranker == "codex":
        results = bm25(docs, [it[field] for it in intents])["results"]
    else:
        results = [cc_keyword_rank(entries, it[field]) for it in intents]
    rows = []
    for it, ranked in zip(intents, results):
        acc = label_fn(it)
        scores = {i: s for i, s in ranked}
        order = [i for i, _ in ranked]
        top = order[:(LIMIT if ranker == "codex" else 5)]  # "top8" fields = top-K returned: Codex 8, Claude Code 5
        first = None
        for i in order:
            if names[i] in acc:
                s = scores[i]
                if ranker == "codex":  # HashSet-order ties -> report both bounds
                    pess = sum(1 for _, x in ranked if x >= s)
                    opt = 1 + sum(1 for _, x in ranked if x > s)
                else:  # stable sort -> deterministic position
                    pess = opt = order.index(i) + 1
                first = (names[i], pess, opt, servers[i])
                break
        acc_top = [i for i in top if names[i] in acc]
        rows.append({
            "id": it["id"], "query": it[field], "acceptable": sorted(acc),
            "n_matches": len(ranked),
            "top8": [f"{servers[i]}:{names[i]}:{scores[i]:.2f}" for i in top],
            "first_ok": first,
            "top1_server": servers[order[0]] if order else None,
            "top1_ok": bool(order) and names[order[0]] in acc,
            "acc_servers_in_top8": sorted({servers[i] for i in acc_top}),
            "n_acc_in_top8": len(acc_top),
            "top8_tokens": sum(toks[i] for i in top),
        })
    return rows


def summarize(rows, label):
    ev = [r for r in rows if r["acceptable"]]
    n = len(ev)
    def rec(k, which=1):
        return sum(1 for r in ev if r["first_ok"] and r["first_ok"][which] <= k) / n
    mrr = sum(1 / r["first_ok"][1] for r in ev if r["first_ok"]) / n
    mrr_opt = sum(1 / r["first_ok"][2] for r in ev if r["first_ok"]) / n
    dup = sum(1 for r in ev if len(r["acc_servers_in_top8"]) > 1) / n
    multi = sum(1 for r in ev if r["n_acc_in_top8"] > 1) / n
    zero = sum(1 for r in ev if r["n_matches"] == 0)
    tok = sum(r["top8_tokens"] for r in rows) / len(rows)
    return {"surface": label, "n_eval": n, "R@1": rec(1), "R@3": rec(3), "R@5": rec(5), "R@8": rec(8),
            "R@1_opt": rec(1, 2), "R@8_opt": rec(8, 2), "MRR": mrr, "MRR_opt": mrr_opt,
            "cross_server_dup_top8": dup, "multi_acceptable_top8": multi, "zero_match_queries": zero,
            "avg_top8_schema_tokens": tok}


def main():
    intents = json.load(open(HERE / "intents.json"))["intents"]
    U = [("unity", t) for t in unity_tools()]
    N = [("nexus-unity", t) for t in nexus_tools()]
    NE = [("nexus-unity", enrich_nexus(t)) for t in nexus_tools()]
    surfaces = {
        "S4 (Unity154+Nexus14)": (U + N, lambda it: set(it["U"]) | set(it["N"])),
        "Unity only (154)": (U, lambda it: set(it["U"])),
        "Nexus only (14)": (N, lambda it: set(it["N"])),
        "S4 + Nexus actions in description (hypothetical)": (U + NE, lambda it: set(it["U"]) | set(it["N"])),
        "Nexus only + actions in description (hypothetical)": (NE, lambda it: set(it["N"])),
    }
    ESCAPE = {"unity_describe", "unity_invoke"}
    for fname, label in (("domain.json", "S6-domain oneOf (13)"), ("domain_flat.json", "S6-domain flat (13)"),
                         ("curated.json", "S6-curated (3 typed + describe/invoke)")):
        tools = catalog_surface(fname)
        if not tools:
            continue
        amap = {t["name"]: tool_actions(t) for t in tools}
        def fn(it, amap=amap):
            ok = {n for n, a in amap.items() if a & set(it["U"])}
            # escape hatch counts only when no typed action covers the intent (it is a discovery hop, not a hit)
            return ok or ({n for n in amap if n in ESCAPE} if it["U"] else set())
        surfaces[label] = ([("nexus-unity", t) for t in tools], fn)
    cat = catalog_surface("domain.json")
    summary, detail = [], {}
    for ranker in ("codex", "claude_code"):
      for field in ("raw", "kw"):
        for label, (entries, fn) in surfaces.items():
            rows = evaluate(label, entries, intents, field, fn, ranker)
            detail[f"{ranker} | {label} [{field}]"] = rows
            summary.append({**summarize(rows, label), "query_form": field, "ranker": ranker})
            if label.startswith("S4"):
                both = [r for r, it in zip(rows, intents) if it["U"] and it["N"]]
                summary[-1]["routing_top1_on_both_labelled"] = {
                    "n": len(both),
                    "unity": sum(1 for r in both if r["top1_server"] == "unity"),
                    "nexus": sum(1 for r in both if r["top1_server"] == "nexus-unity"),
                    "top1_ok_unity": sum(1 for r in both if r["top1_ok"] and r["top1_server"] == "unity"),
                    "top1_ok_nexus": sum(1 for r in both if r["top1_ok"] and r["top1_server"] == "nexus-unity"),
                }
    summary.append({"catalog_surface": "available" if cat else "NOT AVAILABLE (bench/facade_mock/catalog/ absent)"})
    json.dump({"summary": summary, "detail": detail}, open(HERE / "results.json", "w"), indent=1)
    for s in summary:
        print(json.dumps(s))


if __name__ == "__main__":
    sys.exit(main())
