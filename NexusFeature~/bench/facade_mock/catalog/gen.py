# ---------------------------------------------------------- schema builders
def short(s, n=None):
    s = s.strip()
    if n is None: return s
    m = re.match(r"(.+?\.)(\s|$)", s)
    s = m.group(1) if m else s
    return s if len(s) <= n else s[: n - 1] + "…"

def branch(a, desc_len):
    props = {"action": {"const": a["unity_command"]}}
    for p in a["params"]: props[p["name"]] = p["schema"]
    b = {"description": short(a["description"], desc_len), "properties": props,
         "required": ["action"] + a["required"], "additionalProperties": False}
    return b

def mgr_oneof(name, g, desc_len=None):
    acts = list(g["actions"])
    return {"name": name, "description": g["description"],
            "inputSchema": {"type": "object", "properties": {"action": {"type": "string", "enum": acts}},
                            "required": ["action"],
                            "oneOf": [branch(a, desc_len) for a in g["actions"].values()]}}

def merge_props(g):
    props, conflicts = {}, []
    for a in g["actions"].values():
        for p in a["params"]:
            s = copy.deepcopy(p["schema"])
            if p["name"] in props:
                old = props[p["name"]]
                if old.get("type") != s.get("type") or old.get("properties") != s.get("properties"):
                    conflicts.append(p["name"])
                    old.pop("properties", None); old.pop("enum", None); old.pop("items", None)
                    old["type"] = sorted({*([old["type"]] if isinstance(old.get("type"), str) else old.get("type", [])),
                                          *([s["type"]] if isinstance(s.get("type"), str) else s.get("type", []))})
                old["description"] = "See action."  # descriptions differ per action
                old.pop("default", None)
            else:
                props[p["name"]] = s
    return props, sorted(set(conflicts))

def mgr_flat(name, g, mode, desc_len=None):
    props, conflicts = merge_props(g)
    lines = []
    for a in g["actions"].values():
        req = ",".join(a["required"])
        lines.append(f"- {a['unity_command']}: {short(a['description'], desc_len)}" + (f" [requires {req}]" if req and mode == "desc" else ""))
    schema = {"type": "object", "properties": {"action": {"type": "string", "enum": list(g["actions"])}, **props},
              "required": ["action"], "additionalProperties": False}
    if mode == "ifthen":
        schema["allOf"] = [{"if": {"properties": {"action": {"const": a["unity_command"]}}},
                            "then": {"required": a["required"]}} for a in g["actions"].values() if a["required"]]
    return {"name": name, "description": g["description"] + "\nActions:\n" + "\n".join(lines),
            "inputSchema": schema}, conflicts

