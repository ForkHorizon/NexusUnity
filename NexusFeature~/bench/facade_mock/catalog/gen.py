# Method A: name-only heuristics (works on any catalog, incl. `unity list` which hides tags).
# Ordered (first match wins); ambiguity = matched by >=2 rules' domains.
RULES = [
 ("unity_prefab",     r"prefab"),
 ("unity_animation",  r"animat|timeline"),
 ("unity_bake",       r"bake|navmesh|occlusion|lighting"),
 ("unity_package",    r"^package_"),
 ("unity_test",       r"tests?(_|$)"),
 ("unity_build",      r"build"),
 ("unity_settings",   r"_settings$|tags_layers"),
 ("unity_scene",      r"scene(?!_view)|save_all"),
 ("unity_diagnostics",r"console|perf|audit|evals|capture|screenshot|^nexus_"),
 ("unity_code",       r"script|eval|compile|reload_file|^batch$"),
 ("unity_gameobject", r"gameobject|component|transform|parent|^set_(active|tag|layer)$|serialized"),
 ("unity_asset",      r"asset|folder|text_file|material|shader"),
 ("unity_editor",     r"^editor_|menu|selection|search|authoring|autotick|^wait_"),
]
# Hand table: commands the ordered rules put in the wrong domain or miss. Every entry counted.
HAND = {
 "get_import_settings": "unity_asset",    # *_settings rule would say settings
 "set_import_settings": "unity_asset",
 "add_scene_to_build": "unity_build",      # 'scene' and 'build' both match; build wins by order already -> kept for clarity? no: see check below
}

def classify_heuristic(name):
    hits = [d for d, rx in RULES if re.search(rx, name)]
    return (hits[0] if hits else None), hits

# Method B: official tags -> domain (tag-prefix table; a hand table of a different kind).
TAGMAP = [
 ("prefabs","unity_prefab"),("animation","unity_animation"),("baking","unity_bake"),("packages","unity_package"),
 ("tests","unity_test"),("build","unity_build"),("settings","unity_settings"),("scenes","unity_scene"),
 ("observability","unity_diagnostics"),("capture","unity_diagnostics"),("scripts","unity_code"),("batch","unity_code"),
 ("gameobjects","unity_gameobject"),("assets","unity_asset"),("materials","unity_asset"),("editor","unity_editor"),
 ("navigation","unity_editor"),("authoring","unity_editor"),("wait","unity_editor"),("runtime","unity_editor"),
]
def classify_tags(name):
    tags = TAGS.get(name, {}).get("tags", [])
    doms = []
    for t in tags:
        for pre, d in TAGMAP:
            if t == pre or t.startswith(pre + "/"):
                doms.append(d); break
    return (doms[0] if doms else None), tags, doms

# ------------------------------------------------- per-command adapter flags
STATUS_PAIRS = {}
names = set(BYNAME) - {"console"}  # console_status is a cheap probe, not a job poll
for n in names:
    for cand in (n + "_status", n.replace("bake_", "") + "_bake_status", ):
        if cand in names: STATUS_PAIRS[n] = cand
STATUS_PAIRS.update({"bake_occlusion_culling": "occlusion_bake_status", "run_tests": "test_status",
                     "package_add": "package_status", "package_remove": "package_status",
                     "package_resolve": "package_status", "wait_for": "wait_status"})
def flags(c):
    n, ps = c["name"], {p["name"] for p in c["parameters"]}
    f = []
    if n in STATUS_PAIRS: f.append("async_status:" + STATUS_PAIRS[n])
    if re.search(r"capture|screenshot", n): f.append("image_base64")
    if "confirm" in ps: f.append("confirm_gate")
    if re.search(r"^delete_|^clear_|^remove_|unpack|switch_build_target$|package_remove", n): f.append("destructive")
    if n in ("eval", "eval_file", "run_script", "batch", "menu", "reload_file", "reload_file_editor_interpreter",
             "reload_file_player_interpreter"): f.append("code_exec")
    if "dry_run" in ps: f.append("dry_run")
    return f

# --------------------------------------------------------- param mapping
PRIM = {"string": "string", "bool": "boolean", "int": "integer", "long": "integer", "float": "number", "double": "number",
        "string[]": "array<string>", "single[]": "array<number>"}
def param_issue(utype, mschema):
    if utype in PRIM: return None
    if utype == "objectref": return "objectref->string handle (path/guid/globalId/instanceId/hierarchyPath; untyped union)"
    if utype in ("jtoken",): return "polymorphic jtoken->" + str(mschema.get("type"))
    if utype in ("jobject",): return "jobject->" + str(mschema.get("type")) + (" (JSON-in-string)" if mschema.get("type") == "string" else "")
    if utype == "jarray": return "jarray->" + str(mschema.get("type")) + (" (items untyped)" if "items" not in mschema else "")
    if utype == "single[][]": return "single[][]->array<array<number>> (no length constraints)"
    if utype.endswith("input"): return "structured input -> nested object schema" + (" (typed)" if mschema.get("properties") else " (UNTYPED)")
    return f"{utype}->{mschema.get('type')}"

def action_entry(c):
    ms = MCP[c["name"]]["inputSchema"]
    params = []
    for p in c["parameters"]:
        s = ms["properties"].get(p["name"], {})
        params.append({"name": p["name"], "unity_type": p["type"], "schema": s, "required": p["required"],
                       "default": p["default"], "description": p["description"]})
    return {"unity_command": c["name"], "description": c["description"], "params": params,
            "required": [p["name"] for p in c["parameters"] if p["required"]], "flags": flags(c),
            "tags": TAGS.get(c["name"], {}).get("tags", [])}

